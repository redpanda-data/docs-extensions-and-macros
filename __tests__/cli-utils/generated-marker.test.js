const { generatedMarker, GENERATED_MARKER_LEGACY, DOC_TOOLS_VERSION } = require('../../cli-utils/generated-marker')
const { readGeneratedMarker } = require('../../extensions/convert-to-markdown')
const pkg = require('../../package.json')

describe('generatedMarker', () => {
  test('writes the legacy banner, the tool, the generator and the source', () => {
    const line = generatedMarker('property-docs', 'the property definitions in redpanda-data/streaming-enterprise', 'Edit the overrides file.')
    expect(line).toBe(
      `// ${GENERATED_MARKER_LEGACY} Generated by doc-tools (property-docs) from the property definitions in redpanda-data/streaming-enterprise. Edit the overrides file.`
    )
    expect(DOC_TOOLS_VERSION).toBe(pkg.version)
  })

  test('names no version, so a release does not rewrite every generated file', () => {
    const line = generatedMarker('metrics-docs', 'the metrics')
    expect(line).not.toContain(pkg.version)
    expect(line).not.toMatch(/doc-tools \S+ \(/)
  })

  test('omits the hint when none is given, including when Handlebars passes its options object', () => {
    const plain = generatedMarker('metrics-docs', 'the metrics Redpanda exposes.')
    expect(plain).toMatch(/from the metrics Redpanda exposes\.$/)
    expect(generatedMarker('metrics-docs', 'the metrics Redpanda exposes', { hash: {} })).toBe(plain)
  })

  test('round-trips through the convert-to-markdown reader', () => {
    const line = generatedMarker('rpk-docs', 'the rpk command help in redpanda-data/streaming-enterprise', 'See the guide: https://example.test/guide.adoc')
    expect(readGeneratedMarker(line + '\n= Title\n')).toEqual({
      note: line.replace(/^\/\/\s*/, ''),
      generator: 'rpk-docs',
      version: null,
      source: 'the rpk command help in redpanda-data/streaming-enterprise',
    })
  })

  test('refuses a marker with no generator or source', () => {
    expect(() => generatedMarker('', 'x')).toThrow()
    expect(() => generatedMarker('x', '')).toThrow()
  })
})
