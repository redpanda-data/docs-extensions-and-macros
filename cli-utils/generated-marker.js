'use strict'

// The one comment line every doc-tools generator writes at the top of each
// file it produces. convert-to-markdown reads it and reports the provenance
// in the Markdown twins (page-generated-content, page-generated-by,
// page-generated-from, page-generated-sources), so a reader or an agent can
// tell generated text from hand-written text and knows where a fix goes.
//
// The first two sentences are the legacy banner that existing tests and the
// guard-generated-files check already look for, so they never change. The
// version is this package's, which is the version of the generator that ran.
const pkg = require('../package.json')

const GENERATED_MARKER_LEGACY = 'This content is autogenerated. Do not edit manually.'
const DOC_TOOLS_VERSION = pkg.version

/**
 * Build the marker line, without a trailing newline.
 * @param {string} generator - Short generator name, for example `property-docs`
 * @param {string} source - Where the text comes from, as a noun phrase, for
 *   example `the configuration property definitions in redpanda-data/streaming-enterprise`
 * @param {string} [hint] - How to change the text, as one or more sentences
 * @returns {string} `// This content is autogenerated. ... Generated by doc-tools <version> (<generator>) from <source>. <hint>`
 */
function generatedMarker (generator, source, hint) {
  if (!generator || !source) throw new Error('generatedMarker needs a generator and a source')
  const parts = [
    GENERATED_MARKER_LEGACY,
    `Generated by doc-tools ${DOC_TOOLS_VERSION} (${generator}) from ${source.replace(/\.$/, '')}.`,
  ]
  // Handlebars passes its options object as the last argument when a
  // template omits the hint, so only a string counts as one.
  if (typeof hint === 'string' && hint.trim()) parts.push(hint.trim())
  return `// ${parts.join(' ')}`
}

module.exports = { generatedMarker, GENERATED_MARKER_LEGACY, DOC_TOOLS_VERSION }
