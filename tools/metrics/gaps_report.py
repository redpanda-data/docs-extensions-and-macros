#!/usr/bin/env python3
"""Turn metrics-gaps.json into a pull request section and a check result.

`doc-tools generate metrics-docs --source-repo ...` writes metrics-gaps.json
beside its output. It lists every difference between what the Redpanda source
registers and what the cluster exported. The run does not stop for a gap, so
the automated pull request has to show it and wait for a person.

This prints Markdown for the pull request body and exits 1 while any gap is
open, so the workflow can use it as a required check:

  gaps_report.py autogenerated/v26.2.7/metrics/metrics-gaps.json >> body.md

Exit codes: 0 no gaps, 1 gaps that need a person, 2 the file cannot be read.
--no-fail prints the report and exits 0.
Standard library only; Python 3.9+.
"""

import argparse
import json
import sys

KINDS = ("not_scraped", "not_in_source", "type_mismatch", "empty_help", "unresolved")


def load(path):
    with open(path, encoding="utf-8") as handle:
        gaps = json.load(handle)
    if not isinstance(gaps, dict) or any(not isinstance(gaps.get(kind), list) for kind in KINDS):
        raise ValueError("it is not a metrics-gaps.json file")
    return gaps


def render(gaps):
    """Markdown for the pull request body."""
    total = sum(len(gaps[kind]) for kind in KINDS)
    lines = ["## Metrics check against source", ""]
    if not total:
        lines.append("Every metric the Redpanda source registers was exported by the cluster, "
                     "or has a written reason. Nothing needs a person.")
        return "\n".join(lines) + "\n"

    lines += [
        "**%d %s a person before this merges.**" % (total, "gap needs" if total == 1 else "gaps need"),
        "",
        ("The reference may be missing metrics: the source scan could not read some registrations (listed "
         "last). Each metric listed by name is in the data, but could not be confirmed against a running cluster."
         if gaps["unresolved"] else
         "The reference is complete: each metric below is in the data. What is listed here could not be "
         "confirmed against a running cluster."),
        "",
    ]
    if gaps["not_scraped"]:
        lines += [
            "### In source, not exported by the cluster (%d)" % len(gaps["not_scraped"]),
            "",
            "These are documented from source, without labels, and marked `observed: false`. "
            "The cluster setup does not turn on the feature that exports them.",
            "",
            "| Metric | Endpoint | Registered in |",
            "|---|---|---|",
        ]
        lines += ["| `%s` | %s | `%s` |" % (g["name"], g["endpoint"], g.get("defined_in") or "unknown")
                  for g in gaps["not_scraped"]]
        lines += [
            "",
            "To close each one, do one of these in `docs-extensions-and-macros`:",
            "",
            "- Turn the feature on for the metrics cluster in `docker-compose/metrics/` (a property in "
            "`bootstrap-extra.yml`, a service in `metrics.overlay.yml`, or an action in "
            "`cli-utils/generate-cluster-docs.sh`).",
            "- If no cluster can export it, give the reason in `docker-compose/metrics/expected-absent.json`.",
            "",
        ]
    if gaps["not_in_source"]:
        lines += [
            "### Exported by the cluster, not found in source (%d)" % len(gaps["not_in_source"]),
            "",
            "These are documented from the scrape. `tools/metrics/extract_source.py` missed their registration "
            "and needs a fix, or the completeness check cannot be trusted.",
            "",
        ]
        lines += ["- `%s` (%s)" % (g["name"], g["endpoint"]) for g in gaps["not_in_source"]]
        lines.append("")
    if gaps["type_mismatch"]:
        lines += ["### Type differs between source and cluster (%d)" % len(gaps["type_mismatch"]), ""]
        lines += ["- `%s` (%s): %s in source, %s in the scrape" % (g["name"], g["endpoint"], g["source"], g["scrape"])
                  for g in gaps["type_mismatch"]]
        lines.append("")
    if gaps["empty_help"]:
        lines += [
            "### No description in Redpanda (%d)" % len(gaps["empty_help"]),
            "",
            "The fix is a help string in the Redpanda source.",
            "",
        ]
        lines += ["- `%s` (%s)" % (g["name"], g["endpoint"]) for g in gaps["empty_help"]]
        lines.append("")
    if gaps["unresolved"]:
        lines += [
            "### Registrations the source scan could not read (%d)" % len(gaps["unresolved"]),
            "",
            "A metric may be missing from the reference. `tools/metrics/extract_source.py` needs a rule for each.",
            "",
        ]
        lines += ["- `%s:%s`: %s" % (g.get("file"), g.get("line"), g.get("reason")) for g in gaps["unresolved"]]
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("gaps_file", help="metrics-gaps.json from doc-tools generate metrics-docs")
    parser.add_argument("--no-fail", action="store_true", help="exit 0 even when there are gaps")
    args = parser.parse_args(argv)
    try:
        gaps = load(args.gaps_file)
    except (OSError, ValueError) as error:
        sys.stderr.write("error: cannot read %s: %s\n" % (args.gaps_file, error))
        return 2
    sys.stdout.write(render(gaps))
    open_gaps = sum(len(gaps[kind]) for kind in KINDS)
    return 1 if open_gaps and not args.no_fail else 0


if __name__ == "__main__":
    sys.exit(main())
