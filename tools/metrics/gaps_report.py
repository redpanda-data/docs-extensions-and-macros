#!/usr/bin/env python3
"""Turn metrics-gaps.json into a pull request section and a check result.

`doc-tools generate metrics-docs --source-repo ...` writes metrics-gaps.json
beside its output. It lists every difference between what the Redpanda source
registers and what the cluster exported. The run does not stop for a gap, so
the automated pull request has to show it and wait for a person.

This prints Markdown for the pull request body and exits 1 while any gap is
open, so the workflow can use it as a required check:

  gaps_report.py autogenerated/v26.2.7/metrics/metrics-gaps.json >> body.md

Exit codes: 0 no gaps, 1 gaps that need a person, 2 the file cannot be read.
--no-fail prints the report and exits 0.
Standard library only; Python 3.9+.
"""

import argparse
import json
import sys

KINDS = ("not_scraped", "not_in_source", "type_mismatch", "empty_help", "unresolved")
# Added later, so an older gaps file may not have it.
OPTIONAL_KINDS = ("stale_requirements", "stale_overrides", "override_disagrees")
# Listed for the reader and not counted: a writer has completed these.
INFO_KINDS = ("covered_by_override", "redundant_overrides", "retired_overrides")


def load(path):
    with open(path, encoding="utf-8") as handle:
        gaps = json.load(handle)
    if not isinstance(gaps, dict) or any(not isinstance(gaps.get(kind), list) for kind in KINDS):
        raise ValueError("it is not a metrics-gaps.json file")
    for kind in OPTIONAL_KINDS + INFO_KINDS:
        if not isinstance(gaps.get(kind), list):
            gaps[kind] = []
    return gaps


def render(gaps):
    """Markdown for the pull request body."""
    total = sum(len(gaps[kind]) for kind in KINDS + OPTIONAL_KINDS)
    lines = ["## Metrics check against source", ""]
    covered = gaps["covered_by_override"]
    covered_lines = []
    if covered:
        covered_lines = [
            "### Documented from an override, not confirmed by a cluster (%d)" % len(covered),
            "",
            "The cluster did not export these. A writer gave their labels in `docs-data/metric-overrides.json`, "
            "so the reference is complete. Nothing has checked those labels against a running broker. "
            "When the metrics cluster exports a metric, the next run compares the two and the override can go.",
            "",
        ]
        covered_lines += ["- `%s` (%s), registered in `%s`" % (g["name"], g["endpoint"], g.get("defined_in") or "unknown")
                          for g in covered]
        covered_lines.append("")
    if not total:
        lines.append("Every metric the Redpanda source registers was exported by the cluster, has a written reason, "
                     "or is completed by an override. Nothing needs a person.")
        if covered_lines:
            lines += [""] + covered_lines
        cleanup = override_cleanup(gaps)
        if cleanup:
            lines += [""] + cleanup
        return "\n".join(lines).rstrip("\n") + "\n"

    lines += [
        "**%d %s a person before this merges.**" % (total, "gap needs" if total == 1 else "gaps need"),
        "",
        "The reference is complete: each metric below is in the data. What is listed here could not be "
        "confirmed against a running cluster.",
        "",
    ]
    if gaps["not_scraped"]:
        lines += [
            "### In source, not exported by the cluster (%d)" % len(gaps["not_scraped"]),
            "",
            "These are documented from source, without labels, and marked `observed: false`. "
            "The cluster setup does not turn on the feature that exports them.",
            "",
            "| Metric | Endpoint | Registered in |",
            "|---|---|---|",
        ]
        lines += ["| `%s` | %s | `%s` |" % (g["name"], g["endpoint"], g.get("defined_in") or "unknown")
                  for g in gaps["not_scraped"]]
        lines += [
            "",
            "To complete the reference now, add the metric to `docs-data/metric-overrides.json` in this "
            "repository with its `labels`, read from the source file named above. Merge that change into the "
            "branch this pull request targets, in its own pull request, and then run this workflow again for "
            "the tag. The run reads the overrides file from that branch and rebuilds this pull request, so a "
            "commit pushed here is lost. That covers the gap.",
            "",
            "To close it for good, do one of these in `docs-extensions-and-macros`:",
            "",
            "- Turn the feature on for the metrics cluster in `docker-compose/metrics/` (a property in "
            "`bootstrap-extra.yml`, a service in `metrics.overlay.yml`, or an action in "
            "`cli-utils/generate-cluster-docs.sh`), and record what the metric needs in "
            "`docker-compose/metrics/requirements.json`.",
            "- If no cluster can export it, give the reason in `docker-compose/metrics/expected-absent.json`.",
            "",
        ]
    if gaps["not_in_source"]:
        lines += [
            "### Exported by the cluster, not found in source (%d)" % len(gaps["not_in_source"]),
            "",
            "These are documented from the scrape. `tools/metrics/extract_source.py` missed their registration "
            "and needs a fix, or the completeness check cannot be trusted.",
            "",
        ]
        lines += ["- `%s` (%s)" % (g["name"], g["endpoint"]) for g in gaps["not_in_source"]]
        lines.append("")
    if gaps["type_mismatch"]:
        lines += ["### Type differs between source and cluster (%d)" % len(gaps["type_mismatch"]), ""]
        lines += ["- `%s` (%s): %s in source, %s in the scrape" % (g["name"], g["endpoint"], g["source"], g["scrape"])
                  for g in gaps["type_mismatch"]]
        lines.append("")
    if gaps["empty_help"]:
        lines += [
            "### No description in Redpanda (%d)" % len(gaps["empty_help"]),
            "",
            "The fix is a help string in the Redpanda source.",
            "",
        ]
        lines += ["- `%s` (%s)" % (g["name"], g["endpoint"]) for g in gaps["empty_help"]]
        lines.append("")
    if gaps["unresolved"]:
        lines += [
            "### Registrations the source scan could not read (%d)" % len(gaps["unresolved"]),
            "",
            "A metric may be missing from the reference. `tools/metrics/extract_source.py` needs a rule for each.",
            "",
        ]
        lines += ["- `%s:%s`: %s" % (g.get("file"), g.get("line"), g.get("reason")) for g in gaps["unresolved"]]
        lines.append("")
    if gaps["stale_requirements"]:
        lines += [
            "### Requirements that match no metric (%d)" % len(gaps["stale_requirements"]),
            "",
            "These entries in `docker-compose/metrics/requirements.json` name metrics that are not in this "
            "release. The metrics were renamed or removed, so the entries need an update.",
            "",
        ]
        lines += ["- `%s`" % requirement for requirement in gaps["stale_requirements"]]
        lines.append("")
    if gaps["stale_overrides"]:
        lines += [
            "### Overrides that match no metric (%d)" % len(gaps["stale_overrides"]),
            "",
            "These entries in `docs-data/metric-overrides.json` name metrics that this release does not "
            "document. Remove them, or rename them if the metric was renamed. A run with "
            "`--retire-overrides` deletes the ones whose metric the source no longer registers. This run "
            "left these, either because it ran without that option or because the metric is still in source "
            "and has a written reason for not being exported.",
            "",
        ]
        lines += ["- `%s`" % name for name in gaps["stale_overrides"]]
        lines.append("")
    if gaps["override_disagrees"]:
        lines += [
            "### Overrides that disagree with the cluster (%d)" % len(gaps["override_disagrees"]),
            "",
            "The cluster exports these metrics, and the override names labels the cluster does not have. "
            "The cluster is right. Fix or remove the labels in `docs-data/metric-overrides.json`.",
            "",
        ]
        lines += ["- `%s` (%s): %s" % (g["name"], g["endpoint"], ", ".join("`%s`" % label for label in g["labels_not_scraped"]))
                  for g in gaps["override_disagrees"]]
        lines.append("")
    if covered_lines:
        lines += covered_lines
    lines += override_cleanup(gaps)
    return "\n".join(lines).rstrip("\n") + "\n"


def override_cleanup(gaps):
    """Lines about overrides that were deleted, or that can be."""
    lines = []
    for kind, title, intro in (
        ("retired_overrides", "Overrides retired by this run",
         "These parts of `docs-data/metric-overrides.json` no longer changed anything, so this run deleted them. "
         "Nothing to do but check the diff."),
        ("redundant_overrides", "Overrides that can be retired",
         "These parts of `docs-data/metric-overrides.json` no longer change anything. "
         "Run `doc-tools generate metrics-docs` with `--retire-overrides` to delete them."),
    ):
        if gaps[kind]:
            lines += ["### %s (%d)" % (title, len(gaps[kind])), "", intro, ""]
            lines += ["- `%s`: %s" % ("%s.%s" % (g["name"], g["field"]) if g["field"] else g["name"], g["reason"])
                      for g in gaps[kind]]
            lines.append("")
    return lines


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("gaps_file", help="metrics-gaps.json from doc-tools generate metrics-docs")
    parser.add_argument("--no-fail", action="store_true", help="exit 0 even when there are gaps")
    args = parser.parse_args(argv)
    try:
        gaps = load(args.gaps_file)
    except (OSError, ValueError) as error:
        sys.stderr.write("error: cannot read %s: %s\n" % (args.gaps_file, error))
        return 2
    sys.stdout.write(render(gaps))
    open_gaps = sum(len(gaps[kind]) for kind in KINDS + OPTIONAL_KINDS)
    return 1 if open_gaps and not args.no_fail else 0


if __name__ == "__main__":
    sys.exit(main())
