'''
## How it works

Fetches metrics from the brokers and parses out the `# HELP` lines, creating:

- `metrics.json`
- `metrics.adoc`
- `redpanda-metrics-<version>.json`, one entry per metric family (see dataset.py)

These output files are stored in a versioned folder under `docs/autogenerated/<version>/metrics`, based on the major.minor version provided as the first argument.

## Prerequisites

- **Python 3** & **pip** on your system.
- A Redpanda cluster running with the `public_metrics` and `metrics` endpoints exposed at http://localhost:19644/
'''

logging.basicConfig(level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s")

DEFAULT_ADMIN_URL = "http://localhost:19644"

# Exit codes. 1 is the generic failure the script has always used; 2 marks the
# one condition callers most need to tell apart: the cluster answered but
# exposed nothing worth documenting, which must never become an empty page.
EXIT_FAILURE = 1
EXIT_NO_METRICS = 2
# The scrape and the source inventory disagree: a metric the source registers
# was not scraped and has no written reason, or the scrape has one the
# inventory does not know.
EXIT_INCOMPLETE = 4

# The macros load redpanda-metrics-<version>.json only for a release tag.
RELEASE_TAG_RE = re.compile(r"^v\d+\.\d+\.\d+(?:-[\w.]+)?$")

def generated_marker(generator, source, hint=""):
    """Same marker shape as cli-utils/generated-marker.js (no version, so a
    release does not rewrite every file); convert-to-markdown reads it."""
    marker = (
        "// This content is autogenerated. Do not edit manually. "
        f"Generated by doc-tools ({generator}) from {source.rstrip('.')}."
    )
    return marker + (f" {hint.strip()}" if hint.strip() else "")

def fetch_metrics(url):
    """Fetch metrics from the given URL."""
    # Imported here so parsing and rendering can run (and be tested) without
    # the requests package installed.
    import requests
    try:
        response = requests.get(url, timeout=60)
        response.raise_for_status()
        return response.text
    except requests.RequestException as e:
        logging.error(f"Error fetching metrics from {url}: {e}")
        return None

def read_metrics_file(path):
    """Read a Prometheus exposition payload from a file (for tests and offline runs)."""
    try:
        with open(path, encoding="utf-8") as f:
            return f.read()
    except OSError as e:
        logging.error(f"Error reading metrics from {path}: {e}")
        return None

def parse_metrics(metrics_text):
    """
    Parse Prometheus exposition text into a dict:
      metric_name → { description, type, unit, labels: [<label_keys>] }

    - Strips empty `{}` on unlabelled samples
    - Propagates HELP/TYPE from base metrics onto _bucket, _count, _sum
    - Works regardless of # HELP / # TYPE order
    - Captures # UNIT metadata if present
    """

    lines = metrics_text.splitlines()

    # Gather HELP/TYPE metadata in any order
    meta = {}  # name → { 'description': str, 'type': str, 'unit': str }
    for line in lines:
        if line.startswith("# HELP"):
            m = re.match(r"# HELP\s+(\S+)\s+(.+)", line)
            if m:
                name, desc = m.groups()
                meta.setdefault(name, {})['description'] = desc
        elif line.startswith("# TYPE"):
            m = re.match(r"# TYPE\s+(\S+)\s+(\S+)", line)
            if m:
                name, mtype = m.groups()
                meta.setdefault(name, {})['type'] = mtype
        elif line.startswith("# UNIT"):
            m = re.match(r"# UNIT\s+(\S+)\s+(.+)", line)
            if m:
                name, unit = m.groups()
                meta.setdefault(name, {})['unit'] = unit
    # Collect label keys from _every_ sample line
    label_map = {}  # name → set(label_keys)
    for line in lines:
        if line.startswith("#"):
            continue

        # labelled: foo{a="1",b="2"}  42
        m_lbl = re.match(r"^(\S+)\{(.+?)\}\s+(.+)", line)
        if m_lbl:
            name, labels_str, _ = m_lbl.groups()
            keys = [kv.split("=",1)[0] for kv in labels_str.split(",")]
        else:
            # unlabelled, maybe with stray {}: foo{} 42  or just foo 42
            m_unlbl = re.match(r"^(\S+?)(?:\{\})?\s+(.+)", line)
            if not m_unlbl:
                continue
            name, _ = m_unlbl.groups()
            keys = []

        label_map.setdefault(name, set()).update(keys)

    # Propagate HELP/TYPE from base histograms/summaries
    for series in list(label_map):
        for suffix in ("_bucket", "_count", "_sum"):
            if series.endswith(suffix):
                base = series[:-len(suffix)]
                if base in meta:
                    meta.setdefault(series, {}).update(meta[base])
                break

    # Merge into final metrics dict, with warnings
    metrics = {}
    all_names = set(meta) | set(label_map)
    for name in sorted(all_names):
        desc = meta.get(name, {}).get("description")
        mtype = meta.get(name, {}).get("type")
        unit = meta.get(name, {}).get("unit")
        labels = sorted(label_map.get(name, []))

        if desc is None:
            logging.warning(f"Metric '{name}' has samples but no # HELP.")
            desc = ""
        if mtype is None:
            logging.warning(f"Metric '{name}' has no # TYPE entry.")

        metrics[name] = {
            "description": desc,
            "type": mtype,
            "unit": unit,
            "labels": labels
        }

    logging.info(f"Extracted {len(metrics)} metrics.")
    return metrics

def merge_metrics(per_broker):
    """
    Merge the parsed metric sets of several brokers into one.

    Partition-, group- and transform-scoped metrics are exported only by the
    broker that hosts the partition, coordinates the group or runs the
    transform, and that placement differs from one cluster start to the next.
    Scraping one broker therefore misses a run-dependent subset; the union
    across all brokers is stable. Description, type and unit come from the
    first broker that reports the family (they are identical everywhere);
    label keys are the sorted union.
    """
    merged = {}
    for metrics in per_broker:
        for name, data in metrics.items():
            if name not in merged:
                merged[name] = {
                    "description": data.get("description", ""),
                    "type": data.get("type"),
                    "unit": data.get("unit"),
                    "labels": list(data.get("labels") or []),
                }
                continue
            entry = merged[name]
            if not entry["description"] and data.get("description"):
                entry["description"] = data["description"]
            if entry["type"] is None and data.get("type") is not None:
                entry["type"] = data["type"]
            if entry["unit"] is None and data.get("unit") is not None:
                entry["unit"] = data["unit"]
            entry["labels"] = sorted(set(entry["labels"]) | set(data.get("labels") or []))
    return {name: merged[name] for name in sorted(merged)}

def collect(sources, endpoint, texts=None):
    """
    Fetch and parse one endpoint from every source, then merge.

    `sources` is a list of (kind, value) pairs: ("url", admin_base_url) or
    ("file", path). Returns (merged_metrics, failures) where failures lists the
    sources that returned nothing. A source that answers with an empty body
    counts as a failure too. When `texts` is a list, each payload is appended
    to it so the caller can build the family-level dataset from the same scrape.
    """
    parsed = []
    failures = []
    for kind, value in sources:
        if kind == "file":
            text = read_metrics_file(value)
            label = value
        else:
            label = f"{value.rstrip('/')}/{endpoint}/"
            text = fetch_metrics(label)
        if not text:
            failures.append(label)
            continue
        if texts is not None:
            texts.append(text)
        parsed.append(parse_metrics(text))
    return merge_metrics(parsed), failures

def output_asciidoc(metrics, adoc_file):
    """Output metrics as AsciiDoc."""
    with open(adoc_file, "w") as f:
        f.write(generated_marker("metrics-docs", "the metrics Redpanda exposes, defined in redpanda-data/streaming-enterprise") + "\n\n")
        for name, data in metrics.items():
            f.write(f"=== {name}\n\n")
            f.write(f"{data['description']}\n\n")
            f.write(f"*Type*: {data['type']}")
            if data.get("unit"):
                f.write(f"\n\n*Unit*: {data['unit']}")
            if data["labels"]:
                f.write("\n\n*Labels*:\n")
                for label in data["labels"]:
                    f.write(f"\n- `{label}`")
            f.write("\n\n---\n\n")
    logging.info(f"AsciiDoc output written to {adoc_file}")

def output_json(metrics, json_file):
    """Output metrics as JSON."""
    with open(json_file, "w") as f:
        json.dump(metrics, f, indent=4)
    logging.info(f"JSON output written to {json_file}")

def ensure_directory_exists(directory):
    """Ensure the given directory exists."""
    if not os.path.exists(directory):
        os.makedirs(directory)

def count_missing(inventory, public_texts, internal_texts, expected_absent):
    """How many source families are not in the scrape and have no written reason."""
    missing = 0
    for endpoint, texts in (("public", public_texts), ("internal", internal_texts)):
        result = metrics_reconcile.reconcile_endpoint(
            inventory[endpoint], metrics_reconcile.parse_scrape_texts(texts), expected_absent)
        missing += len(result["missing_unexplained"])
    return missing


def check_completeness(inventory, public_texts, internal_texts, expected_absent):
    """Compare the scrape with the source inventory and log every gap.

    Returns the gaps as data, with `count` 0 when the two reconcile. Each
    message says what to do, because the person reading it is usually looking
    at a new metric for the first time.
    """
    gaps = {"count": 0, "not_scraped": [], "not_in_source": [], "type_mismatch": [], "empty_help": [], "unresolved": []}
    for endpoint, texts in (("public", public_texts), ("internal", internal_texts)):
        source = inventory[endpoint]
        result = metrics_reconcile.reconcile_endpoint(
            source, metrics_reconcile.parse_scrape_texts(texts), expected_absent)
        logging.info(
            f"{endpoint}: {result['in_source']} families in source, {result['scraped']} scraped, "
            f"{len(result['missing_explained'])} not scraped with a written reason")
        for name in result["missing_unexplained"]:
            where = source[name].get("defined_in") or "unknown file"
            gaps["not_scraped"].append({"name": name, "endpoint": endpoint, "defined_in": where})
            logging.error(
                f"{name} ({endpoint}) is registered in {where} and was not scraped. "
                "Turn on the feature that exports it in docker-compose/metrics "
                "(a property in bootstrap-extra.yml, a service in metrics.overlay.yml, or an action in "
                "cli-utils/generate-cluster-docs.sh), or give the reason no cluster can export it in "
                "docker-compose/metrics/expected-absent.json.")
        for name in result["scrape_only"]:
            gaps["not_in_source"].append({"name": name, "endpoint": endpoint})
            logging.error(
                f"{name} ({endpoint}) was scraped and is not in the source inventory. "
                "tools/metrics/extract_source.py missed its registration and needs a fix.")
        for item in result["type_mismatch"]:
            gaps["type_mismatch"].append(dict(item, endpoint=endpoint))
            logging.error(
                f"{item['name']} ({endpoint}) is a {item['source']} in source and a {item['scrape']} in the scrape.")
        for name in result["empty_help"]:
            gaps["empty_help"].append({"name": name, "endpoint": endpoint})
            logging.error(f"{name} ({endpoint}) has an empty HELP line.")
    for site in inventory.get("unresolved") or []:
        gaps["unresolved"].append({"file": site.get("file"), "line": site.get("line"), "reason": site.get("reason")})
        logging.error(
            f"A metric registration in {site.get('file')}:{site.get('line')} could not be resolved "
            f"({site.get('reason')}). tools/metrics/extract_source.py needs a rule for it.")
    gaps["count"] = sum(len(value) for key, value in gaps.items() if key != "count")
    return gaps


def parse_args(argv):
    parser = argparse.ArgumentParser(
        description="Scrape /public_metrics and /metrics from a running Redpanda broker and write metrics.json and AsciiDoc."
    )
    parser.add_argument("version", help="Release tag or branch the cluster was started from (names the autogenerated/<version>/metrics folder)")
    parser.add_argument("--admin-url", action="append", dest="admin_urls", metavar="URL",
                        help=f"Base URL of a broker Admin API to scrape. Repeat once per broker; the metric sets are merged. (default: {DEFAULT_ADMIN_URL})")
    parser.add_argument("--output-dir",
                        help="Directory for metrics.json, metrics.adoc and internal-metrics.adoc (default: <cwd>/autogenerated/<version>/metrics)")
    parser.add_argument("--pages-dir", default=os.path.join("modules", "reference", "pages"),
                        help="Directory that receives public-metrics-reference.adoc and internal-metrics-reference.adoc (default: modules/reference/pages)")
    parser.add_argument("--skip-pages", action="store_true",
                        help="Only write the versioned output directory; leave the reference pages alone")
    parser.add_argument("--min-metrics", type=int, default=1,
                        help="Fail (exit 2) when either endpoint yields fewer metrics than this (default: 1)")
    parser.add_argument("--public-file", action="append", dest="public_files", metavar="PATH",
                        help="Read a /public_metrics payload from this file instead of the Admin API (repeatable, one per broker)")
    parser.add_argument("--internal-file", action="append", dest="internal_files", metavar="PATH",
                        help="Read a /metrics payload from this file instead of the Admin API (repeatable, one per broker)")
    parser.add_argument("--inventory", metavar="PATH",
                        help="Source inventory from extract_source.py. Adds the defining file to each metric in "
                             "redpanda-metrics-<version>.json, and the families the source registers that the scrape did not see")
    parser.add_argument("--dataset-dir", metavar="DIR",
                        help="Directory for redpanda-metrics-<version>.json (default: the output directory). "
                             "In a docs repository, pass modules/reference/attachments, where the metric macros read it. "
                             "Used only when the version is a release tag such as v26.2.7")
    parser.add_argument("--expected-absent", metavar="PATH",
                        help="JSON of metric family name or pattern -> reason, for families the cluster cannot export. "
                             "Used with --inventory")
    parser.add_argument("--check-only", action="store_true",
                        help="With --inventory, only compare the scrape with the inventory: print how many families are "
                             "missing, write nothing, and exit 0 when none are. The cluster script polls with this "
                             "until the cluster exports everything")
    parser.add_argument("--strict", action="store_true",
                        help="With --inventory, fail (exit 4) and write nothing when the scrape does not match the "
                             "inventory. Without this flag the gaps are reported in metrics-gaps.json and the output is "
                             "still written, with each unscraped metric taken from source and marked observed: false")
    return parser.parse_args(argv)

def main(argv=None):
    args = parse_args(sys.argv[1:] if argv is None else argv)
    if args.check_only:
        if not args.inventory:
            logging.error("--check-only needs --inventory. Exiting.")
            return EXIT_FAILURE
        # One summary line per poll, not one line per missing family. Errors
        # still show, so an unreadable input says which and why.
        logging.getLogger().setLevel(logging.ERROR)
    tag_modified = args.version.strip()
    if not tag_modified:
        logging.error("Version must not be empty. Exiting.")
        return EXIT_FAILURE

    repo_root = os.getcwd()
    admin_urls = args.admin_urls or [DEFAULT_ADMIN_URL]

    public_sources = [("file", f) for f in args.public_files] if args.public_files else [("url", u) for u in admin_urls]
    internal_sources = [("file", f) for f in args.internal_files] if args.internal_files else [("url", u) for u in admin_urls]

    # Every source must answer. One silent broker would make the merged set
    # depend on which broker happened to be hosting what, which is exactly the
    # nondeterminism scraping every broker is meant to remove.
    public_texts, internal_texts = [], []
    public_metrics, failures = collect(public_sources, "public_metrics", public_texts)
    if failures:
        logging.error(f"No public metrics retrieved from: {', '.join(failures)}. Exiting.")
        return EXIT_FAILURE

    internal_metrics, failures = collect(internal_sources, "metrics", internal_texts)
    if failures:
        logging.error(f"No internal metrics retrieved from: {', '.join(failures)}. Exiting.")
        return EXIT_FAILURE

    # Fail before writing anything: an empty scrape must never turn into an
    # empty page and a green run.
    if len(public_metrics) < args.min_metrics or len(internal_metrics) < args.min_metrics:
        logging.error(
            f"Scrape returned {len(public_metrics)} public and {len(internal_metrics)} internal metrics "
            f"(minimum {args.min_metrics}). The cluster is not exposing metrics yet or is not healthy. "
            "Nothing was written."
        )
        return EXIT_NO_METRICS

    # Versioned output for diffing between releases. Created once the run
    # knows it will write: --check-only and a strict failure write nothing.
    output_dir = args.output_dir or os.path.join(repo_root, "autogenerated", tag_modified, "metrics")

    # The family-level dataset the macros and the docs MCP server read.
    # metrics.json keeps its shape for the tools that already read it.
    inventory = None
    if args.inventory:
        try:
            with open(args.inventory, encoding="utf-8") as f:
                inventory = json.load(f)
        except (OSError, ValueError) as e:
            logging.error(f"Cannot read the source inventory {args.inventory}: {e}. Exiting.")
            return EXIT_FAILURE
        try:
            metrics_dataset.check_inventory(inventory)
        except metrics_dataset.DatasetError as e:
            logging.error(f"The source inventory {args.inventory} is not valid: {e}. Nothing was written.")
            return EXIT_FAILURE
        # An inventory of another release would turn families that release
        # did not have into source-only entries. A commit or branch ref is
        # provenance, not a release, so only two release tags are compared.
        source_ref = inventory.get("ref")
        if source_ref and RELEASE_TAG_RE.match(source_ref) and RELEASE_TAG_RE.match(tag_modified) \
                and source_ref.lstrip("v") != tag_modified.lstrip("v"):
            logging.error(f"The source inventory {args.inventory} is for {source_ref}, not {tag_modified}. Nothing was written.")
            return EXIT_FAILURE
    # Completeness gate. Redpanda exports a family only when the feature behind
    # it is on, so a scrape can be short without looking wrong. With an
    # inventory, every family in source must be scraped or have a written
    # reason, and the scrape must hold nothing the inventory lacks.
    expected_absent = {}
    if args.expected_absent:
        try:
            with open(args.expected_absent, encoding="utf-8") as f:
                expected_absent = json.load(f)
            metrics_reconcile.check_expected_absent(expected_absent)
        except (OSError, ValueError) as e:
            logging.error(f"Cannot read the expected-absent file {args.expected_absent}: {e}. Exiting.")
            return EXIT_FAILURE
    if inventory and args.check_only:
        missing = count_missing(inventory, public_texts, internal_texts, expected_absent)
        print(f"{missing} metric families in source are not exported yet")
        return 0 if missing == 0 else EXIT_INCOMPLETE
    gaps = None
    if inventory:
        gaps = check_completeness(inventory, public_texts, internal_texts, expected_absent)
        if gaps["count"] and args.strict:
            logging.error("The scrape does not match the source inventory. Nothing was written.")
            return EXIT_INCOMPLETE
    generated_from = {"sources": len(public_sources)}
    # The two endpoints are scraped from the same brokers unless files are
    # given per endpoint, and those counts can differ.
    if len(internal_sources) != len(public_sources):
        generated_from["internal_sources"] = len(internal_sources)
    if inventory and inventory.get("ref"):
        generated_from["source_ref"] = inventory["ref"]
    try:
        families = metrics_dataset.build_dataset(
            tag_modified,
            metrics_dataset.merge_families([metrics_dataset.parse_exposition(t) for t in public_texts]),
            metrics_dataset.merge_families([metrics_dataset.parse_exposition(t) for t in internal_texts]),
            inventory=inventory,
            generated_from=generated_from,
        )
    except metrics_dataset.DatasetError as e:
        logging.error(f"Cannot build the dataset. {e}. Nothing was written.")
        return EXIT_FAILURE
    ensure_directory_exists(output_dir)
    if inventory:
        # A family with a written reason is one no cluster exports, so it is
        # listed under excluded and not documented as a metric. A family that
        # was not scraped and has no reason stays, from source and marked
        # observed: false, so the reference never lacks a metric. It is also
        # listed in metrics-gaps.json until the cluster exports it.
        for name in sorted(families["metrics"]):
            entry = families["metrics"][name]
            if entry["observed"]:
                continue
            reason = metrics_reconcile.explain(name, inventory[entry["endpoint"]].get(name, {}), expected_absent)
            if not reason:
                continue
            del families["metrics"][name]
            families["excluded"].append({"name": name, "endpoint": entry["endpoint"], "reason": reason})
            families["counts"][entry["endpoint"]] -= 1
            families["counts"]["source_only"] -= 1
            families["counts"]["excluded"] += 1
        families["excluded"].sort(key=lambda item: item["name"])
    dataset_dir = output_dir
    if args.dataset_dir:
        if RELEASE_TAG_RE.match(tag_modified):
            dataset_dir = args.dataset_dir
            ensure_directory_exists(dataset_dir)
        else:
            logging.info(
                f"{tag_modified} is not a release tag, so the dataset is not written to {args.dataset_dir}. "
                f"The macros only load files for a release tag. It is written to {output_dir}."
            )
    # A branch name such as feature/metrics would put a "/" in the filename.
    # Release tags have none, so their filenames are unchanged.
    dataset_name = re.sub(r"[^A-Za-z0-9._-]", "-", tag_modified)
    dataset_file = os.path.join(dataset_dir, f"redpanda-metrics-{dataset_name}.json")
    with open(dataset_file, "w", encoding="utf-8") as f:
        json.dump(families, f, indent=2)
        f.write("\n")
    logging.info(f"Dataset written to {dataset_file}")
    if gaps is not None:
        # Always written with an inventory, so a pull request check can read
        # it: count 0 means the scrape and the source agree.
        gaps_file = os.path.join(output_dir, "metrics-gaps.json")
        with open(gaps_file, "w", encoding="utf-8") as f:
            json.dump(gaps, f, indent=2)
            f.write("\n")
        if gaps["count"]:
            logging.warning(
                f"{gaps['count']} gaps between the scrape and the source are listed in {gaps_file}. "
                "The output was written. Metrics that were not scraped come from source and have no labels.")

    merged_metrics = {
        "public": public_metrics,
        "internal": internal_metrics
    }

    output_json(merged_metrics, os.path.join(output_dir, "metrics.json"))
    output_asciidoc(public_metrics, os.path.join(output_dir, "metrics.adoc"))
    output_asciidoc(internal_metrics, os.path.join(output_dir, "internal-metrics.adoc"))

    # Reference pages, the historical primary location. CI passes --skip-pages
    # because the committed pages are hand-curated and must not be overwritten.
    if not args.skip_pages:
        reference_pages_dir = os.path.join(repo_root, args.pages_dir)
        ensure_directory_exists(reference_pages_dir)
        output_asciidoc(public_metrics, os.path.join(reference_pages_dir, "public-metrics-reference.adoc"))
        output_asciidoc(internal_metrics, os.path.join(reference_pages_dir, "internal-metrics-reference.adoc"))

    logging.info(f"✅ Generated {len(public_metrics)} public metrics and {len(internal_metrics)} internal metrics from {len(public_sources)} source(s)")
    return 0

if __name__ == "__main__":
    sys.exit(main())
