/* Report hand-written property values in prose, and propose propval: macros.
 *
 * Finds sentences that mention a property (a prop: call or the backticked
 * name) and state one of its values by hand -- "defaults to 128 MiB",
 * "the default is `true`", "minimum 1 minute" -- and checks the written value
 * against the property data for that repo's own version, chosen exactly the
 * way the prop: macro chooses it (loadPropertiesFor in macros/prop.js).
 *
 * Every finding gets one status:
 *
 *   exact        The written text is exactly what propval: renders (human or
 *                raw form). Replacing it changes nothing a reader sees, so
 *                these are the only findings --write applies.
 *   equivalent   Same value, different wording ("7 days" vs "1 week",
 *                "128 MB" vs "128 MiB"). Proposed, never applied.
 *   mismatch     The written value differs from the data. Most likely a real
 *                doc error. Never applied.
 *   unset        The data default is null (not set) but the prose states a
 *                value. Redpanda often computes a runtime fallback for an
 *                unset property (compaction_ctrl_backlog_size uses 10% of
 *                free disk), so a human confirms it against the source.
 *   unverifiable The value could not be compared: unparseable, the property
 *                has no such field, the data does not state it for this
 *                audience (Cloud defaults, ifdef::env-cloud[] blocks), or a
 *                topic property is said to have no default of its own.
 *
 * Tables are scanned: a statement in a cell belongs to the property that opens
 * the row (or cell), and a Default column states the default of the row's
 * property. Table findings are reported, never written.
 *
 * Skipped entirely: delimited blocks (listing, literal, passthrough, comment,
 * fenced code), headings, attribute entries, block titles, comment lines,
 * ifndef::env-cloud[] content on a Cloud page, files carrying the
 * generated-content marker, and the generated paths migrate-property-refs
 * also excludes.
 */

