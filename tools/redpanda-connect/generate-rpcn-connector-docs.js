// Component families with their own reference pages, keyed by the canonical
// type directory from typeDirFor(). Other data keys -- `config`, the bloblang
// functions and methods -- have no per-component page that could include a
// partial, so none is emitted for them.
const CONNECTOR_PAGE_TYPE_DIRS = new Set(CONNECTOR_TYPE_DIRS);

// Blast-radius guard for the post-generation orphan sweep. The sweep blanks
// every description partial the current dataset did not claim, so an
// incomplete dataset (a truncated fetch, a half-succeeded --force-fresh, a
// hand-made subset file) does not look different from "hundreds of connectors
// were deleted upstream" -- and the partials are published content. Blanking
// up to ORPHAN_SWEEP_ALWAYS_ALLOWED files is always fine (that is the size of
// a plausible upstream deletion); above that the sweep also has to stay under
// ORPHAN_SWEEP_MAX_FRACTION of the tree, or it refuses to run and reports
// instead. `pruneOrphanedDescriptions` is the explicit opt-in that overrides
// the refusal once a human has confirmed the dataset is complete.
const ORPHAN_SWEEP_ALWAYS_ALLOWED = 10;
const ORPHAN_SWEEP_MAX_FRACTION = 0.1;

/**
 * Reads a file at `filePath` and registers it as a Handlebars partial called `name`.
 * Throws if the file cannot be read.
 */
function registerPartial(name, filePath) {
  const resolved = path.resolve(filePath);
  let source;
  try {
    source = fs.readFileSync(resolved, 'utf8');
  } catch (err) {
    throw new Error(`Unable to read "${name}" template at ${resolved}: ${err.message}`);
  }
  handlebars.registerPartial(name, source);
}

/**
 * Deep-merge `overrides` into `target`. Only 'description', 'type',
 * 'annotated_field', 'examples', and known nested fields are overridden.
 */
function mergeOverrides(target, overrides) {
  if (!overrides || typeof overrides !== 'object') return target;
  if (!target || typeof target !== 'object') {
    throw new Error('Target must be a valid object');
  }

  // 'summary' earns its place here the hard way: overrides.json has carried
  // summary overrides (zmq4, ffi) that were silently dropped because the key
  // fell through every branch below. Summaries feed page meta descriptions.
  const scalarKeys = ['description', 'summary', 'type', 'annotated_field', 'version'];

  for (const key in overrides) {
    // === Handle annotated_options ===
    if (key === 'annotated_options' && Array.isArray(overrides[key]) && Array.isArray(target[key])) {
      const overrideMap = new Map(overrides[key].map(([name, desc]) => [name, desc]));

      target[key] = target[key].map(([name, desc]) => {
        if (overrideMap.has(name)) {
          return [name, overrideMap.get(name)];
        }
        return [name, desc];
      });

      const existingNames = new Set(target[key].map(([name]) => name));
      for (const [name, desc] of overrides[key]) {
        if (!existingNames.has(name)) {
          target[key].push([name, desc]);
        }
      }
      continue;
    }

    // === Handle examples ===
    if (key === 'examples' && Array.isArray(overrides[key])) {
      // If target[key] is not an array, initialize it
      if (!Array.isArray(target[key])) {
        target[key] = [];
      }
      const overrideMap = new Map(overrides[key].map(o => [o.title, o]));

      target[key] = target[key].map(example => {
        const override = overrideMap.get(example.title);
        if (override) {
          return {
            ...example,
            ...(override.summary && { summary: override.summary }),
            ...(override.config && { config: override.config }),
          };
        }
        return example;
      });

      const existingTitles = new Set(target[key].map(e => e.title));
      for (const example of overrides[key]) {
        if (!existingTitles.has(example.title)) {
          target[key].push(example);
        }
      }
      continue;
    }

    // === Merge arrays of objects with .name ===
    if (Array.isArray(target[key]) && Array.isArray(overrides[key])) {
      target[key] = target[key].map(item => {
        const overrideItem = overrides[key].find(o => o.name === item.name);
        if (overrideItem) {
          scalarKeys.forEach(field => {
            if (Object.hasOwn(overrideItem, field)) {
              item[field] = overrideItem[field];
            }
          });
          if (Object.hasOwn(overrideItem, 'selfManagedOnly')) {
            item.selfManagedOnly = overrideItem.selfManagedOnly;
          }
          return mergeOverrides(item, overrideItem);
        }
        return item;
      });
      continue;
    }

    // === Merge nested objects ===
    if (
      typeof target[key] === 'object' &&
      typeof overrides[key] === 'object' &&
      !Array.isArray(target[key]) &&
      !Array.isArray(overrides[key])
    ) {
      target[key] = mergeOverrides(target[key], overrides[key]);
      continue;
    }

    // === Overwrite scalar keys ===
    if (scalarKeys.includes(key) && Object.hasOwn(overrides, key)) {
      target[key] = overrides[key];
    }
  }

  return target;
}

/**
 * Resolves $ref references in an object by replacing them with their definitions.
 * Supports JSON Pointer style references like "#/definitions/client_certs".
 * 
 * @param {Object} obj - The object to resolve references in
 * @param {Object} root - The root object containing definitions
 * @returns {Object} The object with references resolved
 */
function resolveReferences(obj, root) {
  if (!obj || typeof obj !== 'object') {
    return obj;
  }

  if (Array.isArray(obj)) {
    return obj.map(item => resolveReferences(item, root));
  }

  const result = {};
  
  for (const [key, value] of Object.entries(obj)) {
    if (key === '$ref' && typeof value === 'string') {
      // Handle JSON Pointer style references
      if (value.startsWith('#/')) {
        const path = value.substring(2).split('/');
        let resolved = root;
        
        try {
          for (const segment of path) {
            resolved = resolved[segment];
          }
          
          if (resolved === undefined) {
            throw new Error(`Reference path not found: ${value}`);
          }
          
          // Merge the resolved object, but don't process $ref in the resolved object
          // to avoid infinite recursion
          Object.assign(result, resolved);
        } catch (err) {
          throw new Error(`Failed to resolve reference "${value}": ${err.message}`);
        }
      } else {
        throw new Error(`Unsupported reference format: ${value}. Only JSON Pointer references starting with '#/' are supported.`);
      }
    } else {
      // Recursively resolve references in nested objects
      result[key] = resolveReferences(value, root);
    }
  }
  
  return result;
}

/**
 * Generates documentation files for RPCN connectors using Handlebars templates.
 *
 * Depending on the {@link writeFullDrafts} flag, generates either partial documentation files for connector fields and examples, or full draft documentation for each connector component. Supports merging override data with $ref references and skips draft generation for components marked as deprecated.
 *
 * @param {Object} options - Configuration options for documentation generation.
 * @param {string} options.data - Path to the connector data file (JSON or YAML).
 * @param {string} [options.overrides] - Optional path to a JSON file with override data. Supports $ref references in JSON Pointer format (for example, "#/definitions/client_certs").
 * @param {string} options.template - Path to the main Handlebars template.
 * @param {string} [options.templateIntro] - Path to the intro partial template (used in full draft mode).
 * @param {string} [options.templateFields] - Path to the fields partial template.
 * @param {string} [options.templateExamples] - Path to the examples partial template.
 * @param {boolean} options.writeFullDrafts - If true, generates full draft documentation; otherwise, generates partials.
 * @param {boolean} [options.pruneOrphanedDescriptions=false] - Allow the post-generation sweep to blank description partials absent from the dataset even when they exceed the safety threshold. Only pass this for a dataset confirmed complete.
 * @returns {Promise<Object>} An object summarizing the number and paths of generated partials and drafts.
 *
 * @throws {Error} If reading or parsing input files fails, if template rendering fails for a component, or if $ref references cannot be resolved.
 *
 * @remark
 * When generating full drafts, components with a `status` of `'deprecated'` are skipped.
 */
async function generateRpcnConnectorDocs(options) {
  // Types and output folders for bloblang function/method partials
  const bloblangTypes = [
    { key: 'bloblang-functions', folder: 'bloblang-functions' },
    { key: 'bloblang-methods', folder: 'bloblang-methods' }
  ];
  // Recursively mark is_beta on any field/component with description starting with BETA:
  function markBeta(obj) {
    if (!obj || typeof obj !== 'object') return;
    if (Array.isArray(obj)) {
      obj.forEach(markBeta);
      return;
    }
    // Mark as beta if description starts with 'BETA:' (case-insensitive, trims leading whitespace)
    if (typeof obj.description === 'string' && /^\s*BETA:\s*/i.test(obj.description)) {
      obj.is_beta = true;
    }
    // Recurse into children/config/fields
    if (Array.isArray(obj.children)) obj.children.forEach(markBeta);
    if (obj.config && Array.isArray(obj.config.children)) obj.config.children.forEach(markBeta);
    // For connector/component arrays
    for (const key of Object.keys(obj)) {
      if (Array.isArray(obj[key])) obj[key].forEach(markBeta);
    }
  }

  const {
    data,
    overrides,
    template,            // main Handlebars template (for full-draft mode)
    templateIntro,
    templateFields,
    templateExamples,
    templateMetadata,
    templateDescription,
    templateBloblang,
    writeFullDrafts,
    // Explicit opt-in for the destructive description-partial orphan sweep.
    // Off by default: see ORPHAN_SWEEP_MAX_FRACTION.
    pruneOrphanedDescriptions = false,
    cgoOnly = [],        // Array of cgo-only connectors from cgo binary inspection
    cloudOnly = [],      // Array of cloud-only connectors from cloud binary inspection
    csvMetadata = []     // Array of CSV metadata with support levels
  } = options;

  // Read connector index (JSON or YAML)
  const raw = fs.readFileSync(data, 'utf8');
  const ext = path.extname(data).toLowerCase();
  const dataObj = ext === '.json' ? JSON.parse(raw) : yaml.parse(raw);
  // Mark beta fields/components before overrides
  markBeta(dataObj);

  // Build a Set of cgo-only connector keys for fast lookup
  const cgoOnlySet = new Set();
  if (Array.isArray(cgoOnly)) {
    cgoOnly.forEach(connector => {
      if (connector.type && connector.name) {
        cgoOnlySet.add(`${connector.type}:${connector.name}`);
      }
    });
  }

  // Build a Set of cloud-only connector keys for fast lookup
  const cloudOnlySet = new Set();
  if (Array.isArray(cloudOnly)) {
    cloudOnly.forEach(connector => {
      if (connector.type && connector.name) {
        cloudOnlySet.add(`${connector.type}:${connector.name}`);
      }
    });
  }

  // Build a Map of CSV metadata for fast support level lookup
  const csvMetadataMap = new Map();
  if (Array.isArray(csvMetadata)) {
    csvMetadata.forEach(item => {
      if (item.type && item.name) {
        csvMetadataMap.set(`${item.type}:${item.name}`, item);
      }
    });
  }

  // Apply overrides if provided
  if (overrides && fs.existsSync(overrides)) {
    const ovRaw = fs.readFileSync(overrides, 'utf8');
    const ovObj = JSON.parse(ovRaw);
    // Resolve any $ref references in the overrides
    const resolvedOverrides = resolveReferences(ovObj, ovObj);
    mergeOverrides(dataObj, resolvedOverrides);

    // Special: merge bloblang_methods and bloblang_functions from overrides into main data
    for (const [overrideKey, mainKey] of [
      ['bloblang_methods', 'bloblang-methods'],
      ['bloblang_functions', 'bloblang-functions']
    ]) {
      if (Array.isArray(resolvedOverrides[overrideKey])) {
        if (!Array.isArray(dataObj[mainKey])) dataObj[mainKey] = [];
        // Merge by name
        const mainArr = dataObj[mainKey];
        const overrideArr = resolvedOverrides[overrideKey];
        for (const overrideItem of overrideArr) {
          if (!overrideItem.name) continue;
          const idx = mainArr.findIndex(i => i.name === overrideItem.name);
          if (idx !== -1) {
            mainArr[idx] = { ...mainArr[idx], ...overrideItem };
          } else {
            mainArr.push(overrideItem);
          }
        }
      }
    }
  } else if (overrides) {
    console.log(`Overrides file not found: ${overrides} (skipping)`);
  }

  // Compile the "main" template (used when writeFullDrafts = true)
  const compiledTemplate = handlebars.compile(fs.readFileSync(template, 'utf8'));

  // Determine which templates to use for "fields" and "examples"
  // If templateFields is not provided, fall back to the single `template`.
  // If templateExamples is not provided, skip examples entirely.
  const fieldsTemplatePath   = templateFields   || template;
  const examplesTemplatePath = templateExamples || null;

  // Register partials
  // Always register fields and examples partials (needed for rendering partials even in draft mode)
  if (fieldsTemplatePath) {
    registerPartial('fields', fieldsTemplatePath);
  }
  if (examplesTemplatePath) {
    registerPartial('examples', examplesTemplatePath);
  }

  // Always register the metadata partial. Like fields and examples, it is
  // regenerated on every run so that metadata fields added to a connector's
  // upstream description flow into the docs automatically.
  const metadataTemplatePath = templateMetadata || DEFAULT_METADATA_TEMPLATE;
  registerPartial('metadata', metadataTemplatePath);

  // Always register the description partial. Like metadata, it is regenerated
  // on every run so summary/description edits upstream flow into any page that
  // includes it, instead of being frozen into the page body at first draft.
  const descriptionTemplatePath = templateDescription || DEFAULT_DESCRIPTION_TEMPLATE;
  registerPartial('description', descriptionTemplatePath);

  // In draft mode, also register the intro partial
  if (writeFullDrafts && templateIntro) {
    registerPartial('intro', templateIntro);
  }

  const outputRoot     = path.resolve(process.cwd(), 'modules/components/partials');
  const fieldsOutRoot   = path.join(outputRoot, 'fields');
  const examplesOutRoot = path.join(outputRoot, 'examples');
  const metadataOutRoot = path.join(outputRoot, 'metadata');
  const descriptionOutRoot = path.join(outputRoot, 'descriptions');
  // Drafts go to pages/, not partials/
  const componentsRoot  = writeFullDrafts
    ? path.resolve(process.cwd(), 'modules/components/pages')
    : path.join(outputRoot, 'components');
  const configExamplesRoot = path.resolve(process.cwd(), 'modules/components/examples');

  if (!writeFullDrafts) {
    fs.mkdirSync(fieldsOutRoot,   { recursive: true });
    fs.mkdirSync(examplesOutRoot, { recursive: true });
    fs.mkdirSync(metadataOutRoot, { recursive: true });
    fs.mkdirSync(descriptionOutRoot, { recursive: true });
  }

  // Compile the one-line partial wrappers once, not once per component: they
  // are constants, and the loop runs for every entry in every data key.
  const renderFieldsPartial = handlebars.compile('{{> fields children=config.children}}');
  const renderExamplesPartial = handlebars.compile('{{> examples examples=examples}}');
  const renderMetadataPartial = handlebars.compile('{{> metadata description=description type=type typeDir=typeDir name=name}}');
  const renderDescriptionPartial = handlebars.compile('{{> description summary=summary version=version description=description type=type typeDir=typeDir name=name}}');

  let partialsWritten = 0;
  const descriptionReports = [];
  const lostSectionWarnings = [];
  // typeDir/name keys handled this run; used after the loop to blank
  // description partials orphaned by a connector deleted upstream.
  const visitedDescriptionPartials = new Set();
  let draftsWritten   = 0;
  const partialFiles  = [];
  const draftFiles    = [];

  for (const [type, items] of Object.entries(dataObj)) {
    if (!Array.isArray(items)) continue;

    for (const item of items) {
      if (!item.name) continue;
      const name = item.name;

      // Compute typeDir once for this item (used in templates and file paths)
      const typeDir = type.endsWith('s') ? type : `${type}s`;
      item.typeDir = typeDir;
      // Canonical directory for the partials that pages address by include
      // line. `typeDir` keeps the raw data-key spelling because the fields
      // and examples partials are written under it and published pages
      // already include them by that path; the metadata and description
      // partials are addressed through typeDirFor(), so writing them under
      // anything else leaves the include unresolved. Rate limits are the
      // live case: data key `rate-limits`, include path `rate_limits`.
      const partialTypeDir = typeDirFor(item);

      // Always generate field and example partials (needed for both standalone and draft modes)
      // Render fields using the registered "fields" partial
      const fieldsOut = renderFieldsPartial(item);

      // Render examples only if an examples template was provided
      let examplesOut = '';
      if (examplesTemplatePath) {
        examplesOut = renderExamplesPartial(item);
      }

      if (fieldsOut.trim()) {
        const fPath = path.join(fieldsOutRoot, type, `${name}.adoc`);
        fs.mkdirSync(path.dirname(fPath), { recursive: true });
        fs.writeFileSync(fPath, fieldsOut);
        if (!writeFullDrafts) {
          partialsWritten++;
          partialFiles.push(path.relative(process.cwd(), fPath));
        }
      }

      // Same allowlist as the metadata and description partials below: one
      // gate, one list. The old denylist named only the two bloblang keys, so
      // any other non-page data key (config today, anything added upstream
      // tomorrow) leaked partials no page can include.
      if (examplesOut.trim() && CONNECTOR_PAGE_TYPE_DIRS.has(partialTypeDir)) {
        const ePath = path.join(examplesOutRoot, type, `${name}.adoc`);
        fs.mkdirSync(path.dirname(ePath), { recursive: true });
        fs.writeFileSync(ePath, examplesOut);
        if (!writeFullDrafts) {
          partialsWritten++;
          partialFiles.push(path.relative(process.cwd(), ePath));
        }
      }

      if (CONNECTOR_PAGE_TYPE_DIRS.has(partialTypeDir)) {
        // Render the metadata partial from the connector's description. Only
        // written when the description contains a `== Metadata` section.
        // Rendered inside the guard, not before it: the loop covers every
        // data key, so rendering first meant computing and discarding a
        // partial for every bloblang function, method and config entry.
        const metadataOut = renderMetadataPartial(item);
        // Write under the canonical type directory (not the raw data key) so
        // the file path always matches the include directive built by
        // metadataIncludeLine().
        const mPath = path.join(metadataOutRoot, partialTypeDir, `${name}.adoc`);
        if (metadataOut.trim()) {
          fs.mkdirSync(path.dirname(mPath), { recursive: true });
          if (fs.existsSync(mPath)) {
            // Regeneration is authoritative, but a section vanishing from a
            // published partial is usually content loss, not cleanup: the
            // section either sits outside the upstream description's
            // `== Metadata` block or was hand-migrated from a page, and
            // overwriting drops it without a trace. Warn so the auto-docs PR
            // reviewer can move the content to the connector page or restore
            // it upstream before merging.
            const lost = lostMetadataSections(fs.readFileSync(mPath, 'utf8'), metadataOut);
            if (lost.length) {
              lostSectionWarnings.push({ partial: path.relative(process.cwd(), mPath), sections: lost });
              console.warn(
                `Warning: regenerated metadata partial ${path.relative(process.cwd(), mPath)} ` +
                `drops previously published section(s): ${lost.map((h) => `"${h}"`).join(', ')}. ` +
                'If this content is still wanted, move it to the connector page or restore it ' +
                "in the upstream description's Metadata section."
              );
            }
          }
          fs.writeFileSync(mPath, metadataOut);
          if (!writeFullDrafts) {
            partialsWritten++;
            partialFiles.push(path.relative(process.cwd(), mPath));
          }
        } else if (fs.existsSync(mPath)) {
          // The upstream description dropped its `== Metadata` section, but a
          // previously generated partial is still on disk and an already
          // published page may include it. Deleting the file would break that
          // include (unresolved include directive + build warning), so blank it
          // to a banner-only file: the include still resolves and renders
          // nothing. Log it so a human knows to remove the include line.
          fs.writeFileSync(mPath, STALE_METADATA_PARTIAL);
          console.log(
            `Metadata section removed upstream; emptied stale partial ${path.relative(process.cwd(), mPath)} ` +
            `(remove its include directive from the ${type}/${name} page)`
          );
        }
      }

      // Render the description partial (summary + version + description, with
      // the `== Metadata` block replaced by its own partial include). Emitted
      // for every connector type that has reference pages so a page that
      // includes it always shows the current summary/description instead of
      // first-draft text. The summary is brace-escaped here, the same way
      // renderConnectDescription escapes the description body: the template
      // emits it raw in both the body and the :description: attribute, where
      // an unescaped {placeholder} is silently consumed as a missing
      // attribute reference.
      if (CONNECTOR_PAGE_TYPE_DIRS.has(partialTypeDir)) {
        const descriptionItem = typeof item.summary === 'string'
          ? { ...item, summary: escapePlaceholderBraces(item.summary) }
          : item;
        const descriptionOut = renderDescriptionPartial(descriptionItem);
        visitedDescriptionPartials.add(`${partialTypeDir}/${name}`);
        const dPath = path.join(descriptionOutRoot, partialTypeDir, `${name}.adoc`);
        if (descriptionOut.trim()) {
          fs.mkdirSync(path.dirname(dPath), { recursive: true });
          if (fs.existsSync(dPath)) {
            // Same content-loss check the metadata partial ten lines up has
            // had since #236, for the same reason: regeneration is
            // authoritative, but a section disappearing from a published
            // partial is content loss, not cleanup. Now that pages include
            // these files the risk is real -- a section can only vanish
            // because it left the upstream description or because a human
            // added it here -- so warn before overwriting instead of
            // dropping it without a trace.
            const lost = lostMetadataSections(fs.readFileSync(dPath, 'utf8'), descriptionOut);
            if (lost.length) {
              lostSectionWarnings.push({ partial: path.relative(process.cwd(), dPath), sections: lost });
              console.warn(
                `Warning: regenerated description partial ${path.relative(process.cwd(), dPath)} ` +
                `drops previously published section(s): ${lost.map((h) => `"${h}"`).join(', ')}. ` +
                'If this content is still wanted, move it to the connector page or restore it ' +
                'in the upstream description.'
              );
            }
          }
          fs.writeFileSync(dPath, descriptionOut);
          // The partial now exists for this connector, so a drafted page can
          // include its body instead of freezing the summary and description
          // into the page. Gated on the file actually being written:
          // component families outside CONNECTOR_PAGE_TYPE_DIRS, and
          // connectors with neither summary nor description, keep the inline
          // text rather than getting an include that cannot resolve.
          item.hasDescriptionPartial = true;
          // The attrs region only sets :description: when the connector has a
          // summary, so a page may only replace its header attribute with the
          // include when there is one. Otherwise the page would lose its meta
          // description entirely and keep the inline attribute instead.
          if (typeof item.summary === 'string' && item.summary.trim()) {
            item.hasDescriptionAttrs = true;
          }
          if (!writeFullDrafts) {
            partialsWritten++;
            partialFiles.push(path.relative(process.cwd(), dPath));
          }
          // Long heading-less descriptions render as a wall of text. The fix
          // belongs upstream (add == sections in the Connect source), so
          // surface them here instead of hiding them in the docs build.
          if (
            typeof item.description === 'string' &&
            item.description.length > LONG_HEADINGLESS_THRESHOLD &&
            !hasStructuralHeadings(item.description)
          ) {
            const md = hasMarkdownHeadings(item.description);
            const msg = md
              ? `Markdown-style headings: ${partialTypeDir}/${name} structures its description with ## headings, ` +
                'which render unreliably. Convert them to == sections upstream in the Connect source.'
              : `Long heading-less description: ${partialTypeDir}/${name} ` +
                `(${item.description.length} chars). Consider adding == sections upstream in the Connect source.`;
            descriptionReports.push({ connector: `${partialTypeDir}/${name}`, message: msg });
            console.warn(msg);
          }
          // Headings that start deeper than level one render out of
          // sequence on the page. Upstream fix, so report it.
          const headingDepth = typeof item.description === 'string' ? firstHeadingDepth(item.description) : null;
          if (headingDepth !== null && headingDepth > 2) {
            const seqMsg =
              `Out-of-sequence headings: ${partialTypeDir}/${name} starts at level ${headingDepth - 1} ` +
              '(=== or ### with no parent section). Promote the top headings upstream in the Connect source.';
            descriptionReports.push({ connector: `${partialTypeDir}/${name}`, message: seqMsg });
            console.warn(seqMsg);
          }
        } else if (fs.existsSync(dPath)) {
          // The upstream description disappeared, but a previously generated
          // partial is still on disk and an already published page may include
          // it. Deleting the file would break that include, so blank it to a
          // banner-only file (the include still resolves and renders nothing)
          // and log it so a human knows to remove the include line. Without
          // this, the stale first-draft text would live on disk forever --
          // exactly the drift these partials exist to prevent.
          fs.writeFileSync(dPath, STALE_DESCRIPTION_PARTIAL);
          console.log(
            `Description removed upstream; emptied stale partial ${path.relative(process.cwd(), dPath)} ` +
            `(remove its include directive from the ${type}/${name} page)`
          );
        }
      }

      if (writeFullDrafts) {
        if (String(item.status || '').toLowerCase() === 'deprecated') {
          console.log(`Skipping draft for deprecated component: ${type}/${name}`);
          continue;
        }

        // Check if this connector is cgo-only or cloud-only and mark it
        // Use plural type for CGO/cloud detection (matches test expectations)
        const connectorKey = `${type}:${name}`;
        const isCloudOnly = cloudOnlySet.has(connectorKey);
        const isCgoOnly = cgoOnlySet.has(connectorKey);

        if (isCgoOnly) {
          item.requiresCgo = true;
          // tigerbeetle_cdc also requires idempotency
          if (name === 'tigerbeetle_cdc') {
            item.requiresIdempotency = true;
          }
        }

        if (isCloudOnly) {
          item.cloudOnly = true;
        }

        // Lookup support level from CSV metadata using singular type
        const csvKey = `${item.type}:${name}`;
        const csvData = csvMetadataMap.get(csvKey);
        if (csvData && csvData.support) {
          item.support = csvData.support;
        }

        // typeDir is already computed at the beginning of the loop

        let content;
        try {
          content = compiledTemplate(item);
        } catch (err) {
          throw new Error(`Template render failed for component "${name}": ${err.message}`);
        }

        // Determine output location based on availability
        let destFile;

        if (isCloudOnly) {
          // Cloud-only connectors go to partials/components/cloud-only/{type}s/{name}.adoc
          const cloudOnlyRoot = path.resolve(process.cwd(), 'modules/components/partials/components/cloud-only');
          destFile = path.join(cloudOnlyRoot, typeDir, `${name}.adoc`);
        } else {
          // Regular connectors go to pages/{type}s/{name}.adoc
          destFile = path.join(componentsRoot, typeDir, `${name}.adoc`);
        }

        fs.mkdirSync(path.dirname(destFile), { recursive: true });
        fs.writeFileSync(destFile, content, 'utf8');
        draftsWritten++;
        draftFiles.push({
          path: path.relative(process.cwd(), destFile),
          name: name,
          type: type,
          status: item.status || 'stable',
          requiresCgo: item.requiresCgo || false,
          cloudOnly: item.cloudOnly || false
        });
      }
    }
  }

  // Bloblang function/method partials (only if includeBloblang is true)
  if (options.includeBloblang) {
    for (const { key, folder } of bloblangTypes) {
      const items = dataObj[key];
      if (!Array.isArray(items)) continue;
      const outRoot = path.join(outputRoot, folder);
      fs.mkdirSync(outRoot, { recursive: true });

      // Get current item names
      const currentNames = new Set(items.filter(fn => fn.name).map(fn => fn.name));

      // Delete partials that no longer exist in the data
      if (fs.existsSync(outRoot)) {
        const existingFiles = fs.readdirSync(outRoot).filter(f => f.endsWith('.adoc'));
        for (const file of existingFiles) {
          const name = file.replace('.adoc', '');
          // Skip hand-authored files (by convention, start with underscore)
          if (name.startsWith('_')) {
            console.log(`Skipping hand-authored file: ${file}`);
            continue;
          }
          if (!currentNames.has(name)) {
            const filePath = path.join(outRoot, file);
            fs.unlinkSync(filePath);
            console.log(`Deleted removed ${folder} partial: ${file}`);
          }
        }
      }

      // Use custom or default template
      const bloblangTemplatePath = templateBloblang || path.resolve(__dirname, './templates/bloblang-function.hbs');
      const bloblangTemplate = handlebars.compile(fs.readFileSync(bloblangTemplatePath, 'utf8'));
      for (const fn of items) {
        if (!fn.name) continue;
        const adoc = bloblangTemplate(fn);
        const outPath = path.join(outRoot, `${fn.name}.adoc`);
        fs.writeFileSync(outPath, adoc, 'utf8');
        partialsWritten++;
        partialFiles.push(path.relative(process.cwd(), outPath));
      }
    }

    // Generate overview pages for Bloblang methods and functions
    const guidesRoot = path.join(process.cwd(), 'modules/guides/pages/bloblang');
    fs.mkdirSync(guidesRoot, { recursive: true });

    // Generate methods.adoc with categorized methods
    if (dataObj['bloblang-methods']) {
      const methodsData = dataObj['bloblang-methods'];
      const categoriesMap = new Map();

      // Extract categories and their methods
      for (const method of methodsData) {
        if (!method.name || !method.categories || !Array.isArray(method.categories)) continue;

        for (const cat of method.categories) {
          const categoryName = cat.Category;
          if (!categoryName) continue;

          if (!categoriesMap.has(categoryName)) {
            categoriesMap.set(categoryName, []);
          }
          categoriesMap.get(categoryName).push(method.name);
        }
      }

      // Sort categories and prepare data for template
      const categories = Array.from(categoriesMap.entries())
        .map(([name, methods]) => ({
          name,
          methods: methods.sort()
        }))
        .sort((a, b) => {
          // Special ordering: General first, Deprecated last
          if (a.name === 'General') return -1;
          if (b.name === 'General') return 1;
          if (a.name === 'Deprecated') return 1;
          if (b.name === 'Deprecated') return -1;
          return a.name.localeCompare(b.name);
        });

      const methodsTemplatePath = path.resolve(__dirname, './templates/bloblang-methods-overview.hbs');
      const methodsTemplate = handlebars.compile(fs.readFileSync(methodsTemplatePath, 'utf8'));
      const methodsAdoc = methodsTemplate({ categories });
      const methodsOutPath = path.join(guidesRoot, 'methods.adoc');
      fs.writeFileSync(methodsOutPath, methodsAdoc, 'utf8');
      console.log('Generated methods.adoc overview page');
      partialFiles.push(path.relative(process.cwd(), methodsOutPath));
    }

    // Generate functions.adoc with all functions
    if (dataObj['bloblang-functions']) {
      const functionsData = dataObj['bloblang-functions'];
      const functionNames = functionsData
        .filter(fn => fn.name)
        .map(fn => fn.name)
        .sort();

      const functionsTemplatePath = path.resolve(__dirname, './templates/bloblang-functions-overview.hbs');
      const functionsTemplate = handlebars.compile(fs.readFileSync(functionsTemplatePath, 'utf8'));
      const functionsAdoc = functionsTemplate({ functions: functionNames });
      const functionsOutPath = path.join(guidesRoot, 'functions.adoc');
      fs.writeFileSync(functionsOutPath, functionsAdoc, 'utf8');
      console.log('Generated functions.adoc overview page');
      partialFiles.push(path.relative(process.cwd(), functionsOutPath));
    }
  }

  // Common/Advanced config snippet YAMLs in modules/components/examples
  const commonConfig = helpers.commonConfig;
  const advancedConfig = helpers.advancedConfig;
  for (const [type, items] of Object.entries(dataObj)) {
    if (!Array.isArray(items)) continue;
    for (const item of items) {
      if (!item.name || !item.config || !Array.isArray(item.config.children)) continue;
  // Common config
  const commonYaml = commonConfig(type, item.name, item.config.children);
  const commonPath = path.join(configExamplesRoot, 'common', type, `${item.name}.yaml`);
  fs.mkdirSync(path.dirname(commonPath), { recursive: true });
  fs.writeFileSync(commonPath, commonYaml.toString(), 'utf8');
  partialsWritten++;
  partialFiles.push(path.relative(process.cwd(), commonPath));
  // Advanced config
  const advYaml = advancedConfig(type, item.name, item.config.children);
  const advPath = path.join(configExamplesRoot, 'advanced', type, `${item.name}.yaml`);
  fs.mkdirSync(path.dirname(advPath), { recursive: true });
  fs.writeFileSync(advPath, advYaml.toString(), 'utf8');
  partialsWritten++;
  partialFiles.push(path.relative(process.cwd(), advPath));
    }
  }

  // A connector deleted upstream leaves no dataset entry at all, so the
  // in-loop stale-partial blanking above never sees it and its description
  // partial would keep serving deleted-connector text forever, silently.
  // Sweep the description output root for partials no connector claimed this
  // run and blank them the same way. Skipped in draft mode: drafts run on a
  // filtered dataset (missing connectors only), so "not visited" there means
  // "already documented", not "deleted upstream".
  // The sweep is destructive against published content, so collect the
  // candidates first and check the blast radius before writing anything.
  let orphanSweepSkipped = null;
  if (!writeFullDrafts && fs.existsSync(descriptionOutRoot)) {
    const orphans = [];
    let partialsOnDisk = 0;
    for (const typeDirName of fs.readdirSync(descriptionOutRoot)) {
      const typeDirPath = path.join(descriptionOutRoot, typeDirName);
      if (!fs.statSync(typeDirPath).isDirectory()) continue;
      for (const file of fs.readdirSync(typeDirPath)) {
        if (!file.endsWith('.adoc')) continue;
        partialsOnDisk++;
        const key = `${typeDirName}/${file.slice(0, -'.adoc'.length)}`;
        if (visitedDescriptionPartials.has(key)) continue;
        const orphanPath = path.join(typeDirPath, file);
        // Already blanked on an earlier run: leave it alone so it is not
        // re-reported forever.
        if (fs.readFileSync(orphanPath, 'utf8') === STALE_DESCRIPTION_PARTIAL) continue;
        orphans.push({ key, orphanPath });
      }
    }

    // Over the threshold the far likelier explanation is an incomplete
    // dataset, not a mass upstream deletion, so refuse and report.
    const overBlastRadius =
      orphans.length > ORPHAN_SWEEP_ALWAYS_ALLOWED &&
      orphans.length > partialsOnDisk * ORPHAN_SWEEP_MAX_FRACTION;

    if (orphans.length && overBlastRadius && !pruneOrphanedDescriptions) {
      const percent = Math.round((orphans.length / partialsOnDisk) * 100);
      const msg =
        `Orphan sweep refused: ${orphans.length} of ${partialsOnDisk} description partial(s) (${percent}%) ` +
        `are absent from this run's dataset, over the ${Math.round(ORPHAN_SWEEP_MAX_FRACTION * 100)}% safety ` +
        'threshold. That normally means the dataset is truncated or filtered, not that this many connectors ' +
        'were deleted upstream, and blanking them would wipe published content. Nothing was blanked. ' +
        'Confirm the dataset is complete, then re-run with --prune-orphaned-descriptions to sweep. ' +
        `Affected: ${orphans.slice(0, 10).map((o) => o.key).join(', ')}` +
        (orphans.length > 10 ? `, and ${orphans.length - 10} more` : '');
      orphanSweepSkipped = {
        orphans: orphans.length,
        partialsOnDisk,
        connectors: orphans.map((o) => o.key),
      };
      descriptionReports.push({ connector: 'descriptions (sweep)', message: msg });
      console.error(msg);
    } else {
      for (const { key, orphanPath } of orphans) {
        fs.writeFileSync(orphanPath, STALE_DESCRIPTION_PARTIAL);
        const msg =
          `Connector removed upstream: emptied orphaned description partial ` +
          `${path.relative(process.cwd(), orphanPath)} ` +
          `(remove its include directive and retire the ${key} page)`;
        descriptionReports.push({ connector: key, message: msg });
        console.log(msg);
      }
    }
  }

  // Self-heal published page headers: pages are one-time drafts, so pages
  // created before the template emitted :description: never got one.
  let descriptionBackfill = { backfilled: [], skippedNoSummary: [] };
  if (!writeFullDrafts) {
    descriptionBackfill = backfillPageDescriptions(dataObj);
  }

  return {
    partialsWritten,
    draftsWritten,
    partialFiles,
    draftFiles,
    descriptionReports,
    lostSectionWarnings,
    orphanSweepSkipped,
    descriptionBackfill
  };
}


/**
 * Insert a tagged :description: into existing connector page headers that
 * lack one, sourced from the component's summary in the connector data.
 *
 * Connector pages are one-time first drafts: pages drafted before the
 * template emitted :description: never got one, and nothing rewrote them,
 * so hundreds of published pages ship the generic site meta description
 * even though ~97% of components carry a summary in the source data. This
 * runs on every generation, so the page set self-heals and stays healed.
 *
 * The inserted block matches the connector template's shape: the meta tag
 * region lets single-source stubs inherit the description as a header
 * attribute (see the template comment in connector.hbs).
 *
 * @param {Object} connectorData - Parsed connector data (typed arrays)
 * @param {Object} [options]
 * @param {string} [options.pagesRoot] - Pages directory (default: modules/components/pages under cwd)
 * @param {boolean} [options.dryRun] - Report without writing
 * @returns {{backfilled: string[], skippedNoSummary: string[]}}
 */
function backfillPageDescriptions (connectorData, { pagesRoot, dryRun = false } = {}) {
  const root = pagesRoot || path.resolve(process.cwd(), 'modules/components/pages');
  const results = { backfilled: [], skippedNoSummary: [] };
  if (!fs.existsSync(root)) return results;

  for (const [dataKey, items] of Object.entries(connectorData)) {
    // Membership is tested on the canonical spelling, so the list does not
    // have to carry both spellings of rate limits (which is how one copy of
    // it ended up missing rate limits entirely).
    const canonical = normalizeTypeDir(dataKey);
    if (!CONNECTOR_PAGE_TYPE_DIRS.has(canonical) || !Array.isArray(items)) continue;
    // The data uses 'rate-limits' while the pages directory is
    // 'rate_limits'. Resolve whichever spelling exists on disk.
    const typeDir = fs.existsSync(path.join(root, dataKey)) ? dataKey : canonical;
    for (const item of items) {
      if (!item || !item.name) continue;
      const pagePath = path.join(root, typeDir, `${item.name}.adoc`);
      if (!fs.existsSync(pagePath)) continue;

      const content = fs.readFileSync(pagePath, 'utf8');
      const lines = content.split('\n');
      const headerEnd = lines.findIndex((l) => l.trim() === '');
      const header = lines.slice(0, headerEnd === -1 ? lines.length : headerEnd);
      // A page migrated to the description partial carries the attrs include
      // instead of a literal :description:. Without this arm the backfill
      // splices a competing meta block into every migrated page, so the page
      // ends up with a dead include plus a hand-inserted attribute that
      // silently wins.
      if (header.some((l) => l.startsWith(':description:') || /partial\$descriptions\//.test(l))) continue;

      // Meta descriptions are read as plain text by search results, link
      // previews, and assistants, so the markup comes out mechanically. Same
      // flattener the description partial's attrs region uses, so a page
      // cannot publish one meta description before migrating to the partial
      // and a different one after.
      const summary = flattenToAttributeValue(item.summary);
      if (!summary) {
        results.skippedNoSummary.push(`${typeDir}/${item.name}`);
        continue;
      }

      const insertAt = headerEnd === -1 ? lines.length : headerEnd;
      lines.splice(insertAt, 0, '// tag::meta[]', `:description: ${summary}`, '// end::meta[]');
      if (!dryRun) fs.writeFileSync(pagePath, lines.join('\n'), 'utf8');
      results.backfilled.push(`${typeDir}/${item.name}`);
    }
  }

  if (results.backfilled.length) {
    console.log(`Backfilled :description: into ${results.backfilled.length} connector page header(s) from source summaries`);
  }
  if (results.skippedNoSummary.length) {
    console.warn(
      `\u26a0 ${results.skippedNoSummary.length} connector page(s) lack both a header description and a source summary: ` +
      results.skippedNoSummary.join(', ') +
      '. Author these in the overrides file or upstream.'
    );
  }
  return results;
}

